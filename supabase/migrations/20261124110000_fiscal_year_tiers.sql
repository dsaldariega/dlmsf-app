-- FY-based membership tiers, head limits, and loan privileges.
-- Additive schema change; existing member and transaction records are unchanged.

create table if not exists public.fiscal_years (
  id bigint generated by default as identity primary key,
  code text not null unique,
  start_date date not null,
  end_date date not null,
  status text not null default 'draft' check (status in ('draft','active','closed')),
  max_total_heads integer,
  max_heads_per_member integer,
  head_restrictions_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  activated_at timestamptz,
  check (start_date <= end_date),
  check (max_total_heads is null or max_total_heads >= 0),
  check (max_heads_per_member is null or max_heads_per_member >= 0)
);

create unique index if not exists fiscal_years_one_active_idx on public.fiscal_years ((status)) where status = 'active';

create table if not exists public.tier_settings (
  id bigint generated by default as identity primary key,
  fiscal_year_id bigint not null references public.fiscal_years(id) on delete cascade,
  tier_code text not null,
  display_name text not null,
  enabled boolean not null default true,
  max_heads_per_member integer,
  loan_eligible boolean not null default true,
  loan_limit_mode text not null default 'contributions_only'
    check (loan_limit_mode in ('contributions_only','tier_maximum','unlimited')),
  contribution_multiplier numeric(10,2) not null default 1 check (contribution_multiplier >= 0),
  max_loan_amount numeric(14,2),
  created_at timestamptz not null default now(),
  unique (fiscal_year_id, tier_code),
  check (max_heads_per_member is null or max_heads_per_member >= 0),
  check (max_loan_amount is null or max_loan_amount >= 0)
);

create table if not exists public.member_fiscal_years (
  id bigint generated by default as identity primary key,
  fiscal_year_id bigint not null references public.fiscal_years(id) on delete cascade,
  member_id bigint not null references public.members(id) on delete cascade,
  tier_code text not null,
  assigned_heads integer not null default 1 check (assigned_heads >= 0),
  assigned_at timestamptz not null default now(),
  unique (fiscal_year_id, member_id),
  foreign key (fiscal_year_id, tier_code)
    references public.tier_settings(fiscal_year_id, tier_code)
);

alter table public.fiscal_years enable row level security;
alter table public.tier_settings enable row level security;
alter table public.member_fiscal_years enable row level security;

