-- FY-based membership tiers, head limits, and loan privileges.
-- Additive schema change; existing member and transaction records are unchanged.

create table if not exists public.fiscal_years (
  id bigint generated by default as identity primary key,
  code text not null unique,
  start_date date not null,
  end_date date not null,
  status text not null default 'draft' check (status in ('draft','active','closed')),
  max_total_heads integer,
  max_heads_per_member integer,
  head_restrictions_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  activated_at timestamptz,
  check (start_date <= end_date),
  check (max_total_heads is null or max_total_heads >= 0),
  check (max_heads_per_member is null or max_heads_per_member >= 0)
);

create unique index if not exists fiscal_years_one_active_idx on public.fiscal_years ((status)) where status = 'active';

create table if not exists public.tier_settings (
  id bigint generated by default as identity primary key,
  fiscal_year_id bigint not null references public.fiscal_years(id) on delete cascade,
  tier_code text not null,
  display_name text not null,
  enabled boolean not null default true,
  max_heads_per_member integer,
  loan_eligible boolean not null default true,
  loan_limit_mode text not null default 'contributions_only'
    check (loan_limit_mode in ('contributions_only','tier_maximum','unlimited')),
  contribution_multiplier numeric(10,2) not null default 1 check (contribution_multiplier >= 0),
  max_loan_amount numeric(14,2),
  created_at timestamptz not null default now(),
  unique (fiscal_year_id, tier_code),
  check (max_heads_per_member is null or max_heads_per_member >= 0),
  check (max_loan_amount is null or max_loan_amount >= 0)
);

create table if not exists public.member_fiscal_years (
  id bigint generated by default as identity primary key,
  fiscal_year_id bigint not null references public.fiscal_years(id) on delete cascade,
  member_id bigint not null references public.members(id) on delete cascade,
  tier_code text not null,
  assigned_heads integer not null default 1 check (assigned_heads >= 0),
  assigned_at timestamptz not null default now(),
  unique (fiscal_year_id, member_id),
  foreign key (fiscal_year_id, tier_code)
    references public.tier_settings(fiscal_year_id, tier_code)
);

alter table public.fiscal_years enable row level security;
alter table public.tier_settings enable row level security;
alter table public.member_fiscal_years enable row level security;

revoke all on table public.fiscal_years, public.tier_settings, public.member_fiscal_years from anon;
grant select, insert, update, delete on table public.fiscal_years, public.tier_settings, public.member_fiscal_years to authenticated;

drop policy if exists "Admin manages fiscal years" on public.fiscal_years;
create policy "Admin manages fiscal years" on public.fiscal_years for all to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()));

drop policy if exists "Members read own fiscal years" on public.fiscal_years;
create policy "Members read own fiscal years" on public.fiscal_years for select to authenticated
using (exists (
  select 1 from public.member_fiscal_years mfy
  join public.members m on m.id = mfy.member_id
  where mfy.fiscal_year_id = fiscal_years.id and m.auth_id = (select auth.uid())
));

drop policy if exists "Admin manages tier settings" on public.tier_settings;
create policy "Admin manages tier settings" on public.tier_settings for all to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()));

drop policy if exists "Members read assigned tier settings" on public.tier_settings;
create policy "Members read assigned tier settings" on public.tier_settings for select to authenticated
using (exists (
  select 1 from public.member_fiscal_years mfy
  join public.members m on m.id = mfy.member_id
  where mfy.fiscal_year_id = tier_settings.fiscal_year_id
    and mfy.tier_code = tier_settings.tier_code
    and m.auth_id = (select auth.uid())
));

drop policy if exists "Admin manages member fiscal years" on public.member_fiscal_years;
create policy "Admin manages member fiscal years" on public.member_fiscal_years for all to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()));

drop policy if exists "Members read own fiscal year assignment" on public.member_fiscal_years;
create policy "Members read own fiscal year assignment" on public.member_fiscal_years for select to authenticated
using (exists (
  select 1 from public.members m
  where m.id = member_fiscal_years.member_id and m.auth_id = (select auth.uid())
));

create index if not exists tier_settings_fiscal_year_idx on public.tier_settings(fiscal_year_id);
create index if not exists member_fiscal_years_fiscal_year_idx on public.member_fiscal_years(fiscal_year_id);
create index if not exists member_fiscal_years_member_idx on public.member_fiscal_years(member_id);

create or replace function public.validate_member_fiscal_year_assignment()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_fy public.fiscal_years;
  v_tier public.tier_settings;
  v_total integer;
begin
  select * into v_fy from public.fiscal_years where id = new.fiscal_year_id;
  if not found then raise exception 'Fiscal year not found'; end if;

  select * into v_tier from public.tier_settings
    where fiscal_year_id = new.fiscal_year_id and tier_code = new.tier_code;
  if not found then raise exception 'Tier setting not found for this fiscal year'; end if;

  if not v_tier.enabled then raise exception 'The selected tier is disabled for this fiscal year'; end if;

  if v_fy.head_restrictions_enabled then
    if v_fy.max_heads_per_member is not null and new.assigned_heads > v_fy.max_heads_per_member then
      raise exception 'Assigned heads exceed the fiscal year maximum per member of %', v_fy.max_heads_per_member;
    end if;
    if v_tier.max_heads_per_member is not null and new.assigned_heads > v_tier.max_heads_per_member then
      raise exception 'Assigned heads exceed the % tier maximum of %', v_tier.display_name, v_tier.max_heads_per_member;
    end if;
    if v_fy.max_total_heads is not null then
      select coalesce(sum(assigned_heads),0) into v_total
      from public.member_fiscal_years
      where fiscal_year_id = new.fiscal_year_id and id <> coalesce(new.id, 0);
      if v_total + new.assigned_heads > v_fy.max_total_heads then
        raise exception 'Total assigned heads would exceed the fiscal year limit of %', v_fy.max_total_heads;
      end if;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists member_fiscal_year_assignment_limits on public.member_fiscal_years;
create trigger member_fiscal_year_assignment_limits
before insert or update on public.member_fiscal_years
for each row execute function public.validate_member_fiscal_year_assignment();

create or replace function public.submit_loan_request(p_amount numeric, p_months integer)
returns public.loan_requests
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_mid bigint;
  v_fy public.fiscal_years;
  v_tier public.tier_settings;
  v_assignment public.member_fiscal_years;
  v_paid numeric := 0;
  v_member_limit numeric := 0;
  v_available numeric := 0;
  v_req public.loan_requests;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  select id into v_mid from public.members
  where auth_id = auth.uid() and 'member' = any(roles) limit 1;
  if v_mid is null then raise exception 'Member profile not found' using errcode = '42501'; end if;

  if p_amount is null or p_amount = 'NaN'::numeric or p_amount < 500
     or mod(p_amount, 500) <> 0 or p_months is null
     or p_months not in (1,2,3,4,5,6,9,12,18,24) then
    raise exception 'Invalid amount or duration' using errcode = '22023';
  end if;

  select * into v_fy from public.fiscal_years
  where status = 'active' and current_date between start_date and end_date
  order by id desc limit 1;
  if not found then raise exception 'No active fiscal year is configured for loan requests' using errcode = '22023'; end if;

  select * into v_assignment from public.member_fiscal_years
  where fiscal_year_id = v_fy.id and member_id = v_mid;
  if not found then raise exception 'You have not been assigned a membership tier for the active fiscal year' using errcode = '22023'; end if;

  select * into v_tier from public.tier_settings
  where fiscal_year_id = v_fy.id and tier_code = v_assignment.tier_code;
  if not found or not v_tier.enabled then raise exception 'Your membership tier is not available for the active fiscal year' using errcode = '22023'; end if;
  if not v_tier.loan_eligible then raise exception 'Your membership tier is not eligible for loans in the active fiscal year' using errcode = '22023'; end if;

  perform pg_advisory_xact_lock(v_mid);

  if exists (select 1 from public.loans where borrower_id = v_mid and status <> 'Paid') then
    raise exception 'You already have an ongoing loan. Fully pay your current loan before requesting another one.' using errcode = '23505';
  end if;
  if exists (select 1 from public.loan_requests where member_id = v_mid and status = 'Pending') then
    raise exception 'You already have a pending loan request. Please wait for the administrator to review it.' using errcode = '23505';
  end if;

  select coalesce(sum(wca.amount),0) into v_paid
  from public.weekly_contribution_allocations wca
  where wca.member_id = v_mid and wca.week_start between v_fy.start_date and v_fy.end_date;

  if v_tier.loan_limit_mode = 'contributions_only' then
    v_member_limit := v_paid;
  elsif v_tier.loan_limit_mode = 'tier_maximum' then
    v_member_limit := v_paid * v_tier.contribution_multiplier;
    if v_tier.max_loan_amount is not null then v_member_limit := least(v_member_limit, v_tier.max_loan_amount); end if;
  else
    v_member_limit := coalesce(v_tier.max_loan_amount, 999999999999);
  end if;

  if p_amount > greatest(v_member_limit, 0) then
    raise exception 'Requested amount exceeds your % tier loan limit of % based on your paid contributions and tier settings', v_tier.display_name, v_member_limit using errcode = '22023';
  end if;

  v_available := private.available_fund_balance();
  if p_amount > greatest(v_available, 0) then
    raise exception 'Requested amount exceeds available sinking fund balance' using errcode = '22023';
  end if;

  insert into public.loan_requests(member_id, amount, months)
  values (v_mid, p_amount, p_months) returning * into v_req;
  return v_req;
end;
$$;

revoke execute on function public.submit_loan_request(numeric,integer) from public, anon;
grant execute on function public.submit_loan_request(numeric,integer) to authenticated;
