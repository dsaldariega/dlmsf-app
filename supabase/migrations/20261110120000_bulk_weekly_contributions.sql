-- Bulk weekly contribution generation for administrators.
-- Marks the remaining weekly due for every member as confirmed, creates the
-- per-member allocation records, and writes the requested audit remarks.
create or replace function public.admin_generate_all_weekly_contributions(
  p_week_start date,
  p_paid_on date default current_date
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, private, auth
as $$
declare
  v_member public.members;
  v_due numeric(12,2);
  v_paid numeric(12,2);
  v_remaining numeric(12,2);
  v_submission public.payment_submissions;
  v_members_updated integer := 0;
  v_total_generated numeric(12,2) := 0;
begin
  if auth.uid() is null or not private.is_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;

  if p_week_start is null or extract(dow from p_week_start) <> 0 then
    raise exception 'Choose a valid Sunday collection week' using errcode = '22023';
  end if;

  if p_paid_on is null or p_paid_on > current_date then
    raise exception 'Payment date cannot be in the future' using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('weekly-contribution-all:' || p_week_start::text, 0)
  );

  for v_member in
    select *
    from public.members
    order by id
  loop
    v_due := coalesce(v_member.heads, 0) * 50;

    select coalesce(sum(amount), 0)
      into v_paid
    from public.weekly_contribution_allocations
    where member_id = v_member.id
      and week_start = p_week_start;

    v_remaining := greatest(v_due - v_paid, 0);

    if v_remaining > 0 then
      insert into public.payment_submissions(
        member_id,
        payment_type,
        amount,
        paid_on,
        week_start,
        reference,
        status,
        submitted_at,
        reviewed_at,
        reviewed_by,
        admin_remarks
      )
      values (
        v_member.id,
        'Weekly',
        v_remaining,
        p_paid_on,
        p_week_start,
        'Generated for all members',
        'Confirmed',
        now(),
        now(),
        auth.uid(),
        'Generated by administrator for the full weekly collection.'
      )
      returning * into v_submission;

      insert into public.weekly_contribution_allocations(
        payment_submission_id,
        member_id,
        week_start,
        amount
      )
      values (
        v_submission.id,
        v_member.id,
        p_week_start,
        v_remaining
      );

      insert into public.payments_audit_log(
        member_id,
        amount,
        week_start,
        action,
        remarks,
        created_date
      )
      values (
        v_member.id,
        v_remaining,
        p_week_start,
        'Weekly Contribution Recorded',
        format(
          '%s paid weekly dues of PHP %s.',
          v_member.name,
          to_char(v_remaining, 'FM999,999,990.00')
        ),
        now()
      );

      v_members_updated := v_members_updated + 1;
      v_total_generated := v_total_generated + v_remaining;
    end if;
  end loop;

  return jsonb_build_object(
    'weekStart', p_week_start,
    'membersUpdated', v_members_updated,
    'totalGenerated', v_total_generated
  );
end;
$$;

revoke all on function public.admin_generate_all_weekly_contributions(date,date) from public, anon;
grant execute on function public.admin_generate_all_weekly_contributions(date,date) to authenticated, service_role;
