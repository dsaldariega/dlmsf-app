-- Member self-service workflows. Apply via the normal Supabase migration pipeline.
create table if not exists public.loan_requests (
 id bigint generated by default as identity primary key,
 member_id bigint not null references public.members(id) on delete cascade,
 amount numeric(12,2) not null check(amount>=500 and mod(amount,500)=0),
 months integer not null check(months in(1,2,3,4,5,6,9,12,18,24)),
 status text not null default 'Pending' check(status in('Pending','Approved','Rejected')),
 requested_at timestamptz not null default now(), reviewed_at timestamptz, reviewed_by uuid,
 admin_remarks text, loan_id bigint references public.loans(id) on delete set null
);
create unique index if not exists loan_requests_one_pending on public.loan_requests(member_id) where status='Pending';
create table if not exists public.payment_submissions (
 id bigint generated by default as identity primary key,
 member_id bigint not null references public.members(id) on delete cascade,
 payment_type text not null check(payment_type in('Weekly','Loan')),
 amount numeric(12,2) not null check(amount>0), paid_on date not null default current_date,
 week_start date, loan_id bigint references public.loans(id) on delete set null, reference text,
 status text not null default 'Pending' check(status in('Pending','Confirmed','Rejected')),
 submitted_at timestamptz not null default now(), reviewed_at timestamptz, reviewed_by uuid, admin_remarks text,
 constraint payment_submission_target check((payment_type='Weekly' and week_start is not null and extract(dow from week_start)=0 and loan_id is null) or (payment_type='Loan' and loan_id is not null and week_start is null))
);
create unique index if not exists payment_submissions_week_unique on public.payment_submissions(member_id,week_start) where payment_type='Weekly' and status<>'Rejected';
create unique index if not exists payment_submissions_loan_pending_unique on public.payment_submissions(member_id,loan_id) where payment_type='Loan' and status='Pending';
create index if not exists loan_requests_status_idx on public.loan_requests(status,requested_at desc);
create index if not exists payment_submissions_status_idx on public.payment_submissions(status,submitted_at desc);
alter table public.loan_requests enable row level security;
alter table public.payment_submissions enable row level security;
drop policy if exists "Members view own loan requests or admins view all" on public.loan_requests;
create policy "Members view own loan requests or admins view all" on public.loan_requests for select to authenticated using((select private.is_admin()) or exists(select 1 from public.members m where m.id=member_id and m.auth_id=(select auth.uid())));
drop policy if exists "Members view own payment submissions or admins view all" on public.payment_submissions;
create policy "Members view own payment submissions or admins view all" on public.payment_submissions for select to authenticated using((select private.is_admin()) or exists(select 1 from public.members m where m.id=member_id and m.auth_id=(select auth.uid())));
revoke all on public.loan_requests,public.payment_submissions from anon,authenticated;
grant select on public.loan_requests,public.payment_submissions to authenticated;

alter table public.loans_audit_log add column if not exists member_id bigint references public.members(id) on delete set null;
update public.loans_audit_log a set member_id=m.id from (select name,min(id) as id from public.members group by name having count(*)=1) m where a.member_id is null and a.borrower_name=m.name;
drop policy if exists "Members can view own loan audit rows" on public.loans_audit_log;
create policy "Members can view own loan audit rows" on public.loans_audit_log for select to authenticated using((select private.is_admin()) or exists(select 1 from public.members m where m.id=loans_audit_log.member_id and m.auth_id=(select auth.uid())));

create or replace function public.create_loan(p_borrower_id bigint,p_amount numeric,p_months integer)
returns public.loans language plpgsql set search_path=pg_catalog as $$
declare v_loan public.loans; v_name text; v_interest numeric(12,2); v_total numeric(12,2); v_monthly numeric(12,2);
begin
 if auth.uid() is null or not private.is_admin() then raise exception 'Administrator access required' using errcode='42501'; end if;
 select name into v_name from public.members where id=p_borrower_id;
 if not found then raise exception 'Borrower does not exist' using errcode='23503'; end if;
 if p_amount is null or p_amount<500 or mod(p_amount,500)<>0 or p_months not in(1,2,3,4,5,6,9,12,18,24) then raise exception 'Invalid amount or duration' using errcode='22023'; end if;
 v_interest:=round(p_amount*0.05*p_months,2); v_total:=round(p_amount+v_interest,2); v_monthly:=round(v_total/p_months,2);
 insert into public.loans(borrower_id,amount,interest,total,monthly,months,status) values(p_borrower_id,p_amount,v_interest,v_total,v_monthly,p_months,'Ongoing') returning * into v_loan;
 insert into public.loans_audit_log(member_id,borrower_name,amount,interest,total,monthly,months,action,remarks,created_date) values(p_borrower_id,v_name,v_loan.amount,v_loan.interest,v_loan.total,v_loan.monthly,v_loan.months,'New Loan Created',format('New loan created for %s months',p_months),current_date);
 return v_loan;
end $$;

create or replace function public.submit_loan_request(p_amount numeric,p_months integer)
returns public.loan_requests language plpgsql security definer set search_path=pg_catalog as $$
declare v_mid bigint; v_available numeric; v_req public.loan_requests;
begin
 if auth.uid() is null then raise exception 'Authentication required' using errcode='42501'; end if;
 select id into v_mid from public.members where auth_id=auth.uid() and 'member'=any(roles) limit 1;
 if v_mid is null then raise exception 'Member profile not found' using errcode='42501'; end if;
 if p_amount is null or p_amount<500 or mod(p_amount,500)<>0 or p_months not in(1,2,3,4,5,6,9,12,18,24) then raise exception 'Invalid amount or duration' using errcode='22023'; end if;
 perform pg_advisory_xact_lock(v_mid);
 if exists(select 1 from public.loan_requests where member_id=v_mid and status='Pending') then raise exception 'You already have a pending loan request' using errcode='23505'; end if;
 select coalesce((select sum(amount) from public.payments),0)+coalesce((select sum(amount) from public.loan_payments),0)-coalesce((select sum(amount) from public.loans),0) into v_available;
 if p_amount>greatest(v_available,0) then raise exception 'Requested amount exceeds available sinking fund balance' using errcode='22023'; end if;
 insert into public.loan_requests(member_id,amount,months) values(v_mid,p_amount,p_months) returning * into v_req; return v_req;
end $$;

create or replace function public.review_loan_request(p_request_id bigint,p_decision text,p_remarks text default null)
returns public.loan_requests language plpgsql security definer set search_path=pg_catalog as $$
declare v_req public.loan_requests; v_available numeric; v_loan public.loans;
begin
 if auth.uid() is null or not private.is_admin() then raise exception 'Administrator access required' using errcode='42501'; end if;
 if p_decision not in('Approved','Rejected') then raise exception 'Invalid decision' using errcode='22023'; end if;
 select * into v_req from public.loan_requests where id=p_request_id for update;
 if not found then raise exception 'Request not found' using errcode='P0002'; end if;
 if v_req.status<>'Pending' then raise exception 'Request already reviewed' using errcode='55000'; end if;
 if p_decision='Approved' then
  select coalesce((select sum(amount) from public.payments),0)+coalesce((select sum(amount) from public.loan_payments),0)-coalesce((select sum(amount) from public.loans),0) into v_available;
  if v_req.amount>greatest(v_available,0) then raise exception 'Insufficient available sinking fund balance' using errcode='22023'; end if;
  select * into v_loan from public.create_loan(v_req.member_id,v_req.amount,v_req.months);
  update public.loan_requests set status='Approved',reviewed_at=now(),reviewed_by=auth.uid(),admin_remarks=nullif(trim(p_remarks),''),loan_id=v_loan.id where id=p_request_id returning * into v_req;
 else
  update public.loan_requests set status='Rejected',reviewed_at=now(),reviewed_by=auth.uid(),admin_remarks=nullif(trim(p_remarks),'') where id=p_request_id returning * into v_req;
 end if;
 return v_req;
end $$;

create or replace function public.submit_payment(p_type text,p_amount numeric,p_paid_on date,p_week_start date,p_loan_id bigint,p_reference text)
returns public.payment_submissions language plpgsql security definer set search_path=pg_catalog as $$
declare v_mid bigint; v_heads integer; v_loan public.loans; v_paid numeric; v_sub public.payment_submissions;
begin
 if auth.uid() is null then raise exception 'Authentication required' using errcode='42501'; end if;
 select id,heads into v_mid,v_heads from public.members where auth_id=auth.uid() and 'member'=any(roles) limit 1;
 if v_mid is null then raise exception 'Member profile not found' using errcode='42501'; end if;
 if p_amount is null or p_amount<=0 or p_paid_on is null then raise exception 'Enter a valid amount and date' using errcode='22023'; end if;
 if p_type='Weekly' then
  if p_week_start is null or extract(dow from p_week_start)<>0 or p_loan_id is not null or p_amount>v_heads*50 then raise exception 'Invalid weekly contribution amount or Sunday' using errcode='22023'; end if;
 elsif p_type='Loan' then
  if p_loan_id is null or p_week_start is not null then raise exception 'Select a loan' using errcode='22023'; end if;
  select * into v_loan from public.loans where id=p_loan_id and borrower_id=v_mid and status<>'Paid';
  if not found then raise exception 'Active loan not found' using errcode='P0002'; end if;
  select coalesce(sum(amount),0) into v_paid from public.loan_payments where loan_id=p_loan_id;
  if p_amount>greatest(v_loan.total-v_paid,0) then raise exception 'Payment exceeds remaining loan balance' using errcode='22023'; end if;
 else raise exception 'Invalid payment type' using errcode='22023'; end if;
 insert into public.payment_submissions(member_id,payment_type,amount,paid_on,week_start,loan_id,reference) values(v_mid,p_type,p_amount,p_paid_on,p_week_start,p_loan_id,nullif(trim(p_reference),'')) returning * into v_sub;
 return v_sub;
end $$;

create or replace function public.review_payment_submission(p_submission_id bigint,p_decision text,p_remarks text default null)
returns public.payment_submissions language plpgsql security definer set search_path=pg_catalog as $$
declare v_sub public.payment_submissions; v_total numeric; v_paid numeric;
begin
 if auth.uid() is null or not private.is_admin() then raise exception 'Administrator access required' using errcode='42501'; end if;
 if p_decision not in('Confirmed','Rejected') then raise exception 'Invalid decision' using errcode='22023'; end if;
 select * into v_sub from public.payment_submissions where id=p_submission_id for update;
 if not found then raise exception 'Submission not found' using errcode='P0002'; end if;
 if v_sub.status<>'Pending' then raise exception 'Submission already reviewed' using errcode='55000'; end if;
 if p_decision='Confirmed' and v_sub.payment_type='Loan' then
  insert into public.loan_payments(loan_id,member_id,amount,paid_at) values(v_sub.loan_id,v_sub.member_id,v_sub.amount,v_sub.paid_on);
  select total into v_total from public.loans where id=v_sub.loan_id for update;
  select coalesce(sum(amount),0) into v_paid from public.loan_payments where loan_id=v_sub.loan_id;
  if v_paid>=v_total then update public.loans set status='Paid' where id=v_sub.loan_id; end if;
 end if;
 update public.payment_submissions set status=p_decision,reviewed_at=now(),reviewed_by=auth.uid(),admin_remarks=nullif(trim(p_remarks),'') where id=p_submission_id returning * into v_sub;
 return v_sub;
end $$;

revoke all on function public.submit_loan_request(numeric,integer),public.review_loan_request(bigint,text,text),public.submit_payment(text,numeric,date,date,bigint,text),public.review_payment_submission(bigint,text,text) from public,anon;
grant execute on function public.submit_loan_request(numeric,integer),public.review_loan_request(bigint,text,text),public.submit_payment(text,numeric,date,date,bigint,text),public.review_payment_submission(bigint,text,text) to authenticated;
