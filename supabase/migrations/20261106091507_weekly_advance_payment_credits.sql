
create table if not exists public.weekly_contribution_allocations (
  id bigint generated by default as identity primary key,
  payment_submission_id bigint not null references public.payment_submissions(id) on delete cascade,
  member_id bigint not null references public.members(id) on delete cascade,
  week_start date not null check (extract(dow from week_start) = 0),
  amount numeric(12,2) not null check (amount > 0),
  created_at timestamptz not null default now(),
  unique(payment_submission_id, week_start)
);
create index if not exists weekly_contribution_allocations_member_week_idx
  on public.weekly_contribution_allocations(member_id, week_start);
alter table public.weekly_contribution_allocations enable row level security;
drop policy if exists "Members view own weekly allocations or admins view all" on public.weekly_contribution_allocations;
create policy "Members view own weekly allocations or admins view all"
  on public.weekly_contribution_allocations for select to authenticated
  using ((select private.is_admin()) or exists (
    select 1 from public.members m
    where m.id = member_id and m.auth_id = (select auth.uid())
  ));
revoke all on public.weekly_contribution_allocations from anon, authenticated;
grant select on public.weekly_contribution_allocations to authenticated;

-- Backfill historical confirmed weekly submissions as credits against their recorded week.
insert into public.weekly_contribution_allocations(payment_submission_id, member_id, week_start, amount)
select s.id, s.member_id, s.week_start, s.amount
from public.payment_submissions s
where s.payment_type = 'Weekly' and s.status = 'Confirmed'
on conflict (payment_submission_id, week_start) do nothing;

-- Allow repeated confirmed advance payments, but only one weekly payment awaiting review per member.
drop index if exists public.payment_submissions_week_unique;
create unique index if not exists payment_submissions_one_pending_weekly
  on public.payment_submissions(member_id)
  where payment_type = 'Weekly' and status = 'Pending';

create or replace function public.submit_payment(
  p_type text, p_amount numeric, p_paid_on date, p_week_start date, p_loan_id bigint, p_reference text
)
returns public.payment_submissions
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_mid bigint;
  v_heads integer;
  v_week_start date;
  v_week_credit numeric;
  v_week_due numeric;
  v_loan public.loans;
  v_paid numeric;
  v_remaining numeric;
  v_sub public.payment_submissions;
begin
  if auth.uid() is null then raise exception 'Authentication required' using errcode = '42501'; end if;
  select id, heads into v_mid, v_heads
  from public.members
  where auth_id = auth.uid() and 'member' = any(roles)
  limit 1;
  if v_mid is null then raise exception 'Member profile not found' using errcode = '42501'; end if;
  if p_amount is null or p_amount = 'NaN'::numeric or p_amount <= 0
     or p_paid_on is null or p_paid_on > current_date then
    raise exception 'Enter a valid amount and payment date' using errcode = '22023';
  end if;

  if p_type = 'Weekly' then
    if p_week_start is null or extract(dow from p_week_start) <> 0
       or p_week_start > current_date or p_loan_id is not null then
      raise exception 'Choose a valid collection Sunday' using errcode = '22023';
    end if;
    perform pg_advisory_xact_lock(v_mid);
    if exists(select 1 from public.payment_submissions
              where member_id = v_mid and payment_type = 'Weekly' and status = 'Pending') then
      raise exception 'You already have a weekly payment awaiting review' using errcode = '23505';
    end if;
    v_week_start := p_week_start;
    v_week_due := v_heads * 50;
    if v_week_due <= 0 then raise exception 'Your weekly obligation is not configured' using errcode = '22023'; end if;
    -- Skip weeks already fully covered; a partial credit remains on the first uncovered week.
    for i in 1..520 loop
      select coalesce(sum(amount), 0) into v_week_credit
      from public.weekly_contribution_allocations
      where member_id = v_mid and week_start = v_week_start;
      exit when v_week_credit < v_week_due;
      v_week_start := v_week_start + 7;
    end loop;
    v_remaining := greatest(v_week_due - v_week_credit, 0);
    if p_amount < v_remaining then
      raise exception 'Payment must cover at least the remaining weekly obligation of %', v_remaining using errcode = '22023';
    end if;
  elsif p_type = 'Loan' then
    if p_loan_id is null or p_week_start is not null then raise exception 'Select a loan' using errcode = '22023'; end if;
    select * into v_loan from public.loans
    where id = p_loan_id and borrower_id = v_mid and status <> 'Paid'
    for update;
    if not found then raise exception 'Active loan not found' using errcode = 'P0002'; end if;
    select coalesce(sum(amount), 0) into v_paid from public.loan_payments where loan_id = p_loan_id;
    v_remaining := greatest(v_loan.total - v_paid, 0);
    if p_amount > v_remaining then raise exception 'Payment exceeds remaining loan balance' using errcode = '22023'; end if;
    if p_amount < least(coalesce(v_loan.monthly, 0), v_remaining) then
      raise exception 'Payment must be at least the monthly due of %', least(coalesce(v_loan.monthly, 0), v_remaining) using errcode = '22023';
    end if;
  else
    raise exception 'Invalid payment type' using errcode = '22023';
  end if;

  insert into public.payment_submissions(member_id, payment_type, amount, paid_on, week_start, loan_id, reference)
  values (v_mid, p_type, p_amount, p_paid_on, case when p_type = 'Weekly' then v_week_start else null end,
          p_loan_id, nullif(trim(p_reference), ''))
  returning * into v_sub;
  return v_sub;
end;
$$;

create or replace function public.review_payment_submission(p_submission_id bigint, p_decision text, p_remarks text default null)
returns public.payment_submissions
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_sub public.payment_submissions;
  v_total numeric;
  v_paid numeric;
  v_heads integer;
  v_week_start date;
  v_week_due numeric;
  v_week_credit numeric;
  v_to_allocate numeric;
  v_remaining numeric;
  v_loan public.loans;
begin
  if auth.uid() is null or not private.is_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;
  if p_decision is null or p_decision not in ('Confirmed', 'Rejected') then
    raise exception 'Invalid decision' using errcode = '22023';
  end if;
  select * into v_sub from public.payment_submissions where id = p_submission_id for update;
  if not found then raise exception 'Submission not found' using errcode = 'P0002'; end if;
  if v_sub.status <> 'Pending' then raise exception 'Submission already reviewed' using errcode = '55000'; end if;

  if p_decision = 'Confirmed' and v_sub.payment_type = 'Weekly' then
    perform pg_advisory_xact_lock(v_sub.member_id);
    select heads into v_heads from public.members where id = v_sub.member_id;
    v_week_due := v_heads * 50;
    v_week_start := v_sub.week_start;
    v_remaining := v_sub.amount;
    for i in 1..520 loop
      exit when v_remaining <= 0;
      select coalesce(sum(amount), 0) into v_week_credit
      from public.weekly_contribution_allocations
      where member_id = v_sub.member_id and week_start = v_week_start;
      v_to_allocate := least(v_remaining, greatest(v_week_due - v_week_credit, 0));
      if v_to_allocate > 0 then
        insert into public.weekly_contribution_allocations(payment_submission_id, member_id, week_start, amount)
        values (v_sub.id, v_sub.member_id, v_week_start, v_to_allocate);
        v_remaining := v_remaining - v_to_allocate;
      end if;
      v_week_start := v_week_start + 7;
    end loop;
    if v_remaining > 0 then raise exception 'Unable to allocate the full weekly payment' using errcode = '22023'; end if;
  elsif p_decision = 'Confirmed' and v_sub.payment_type = 'Loan' then
    select * into v_loan from public.loans
    where id = v_sub.loan_id and borrower_id = v_sub.member_id for update;
    if not found then raise exception 'Loan no longer exists for this member' using errcode = 'P0002'; end if;
    select coalesce(sum(amount), 0) into v_paid from public.loan_payments where loan_id = v_sub.loan_id;
    v_total := greatest(v_loan.total - v_paid, 0);
    if v_sub.amount > v_total then raise exception 'Payment exceeds the remaining loan balance' using errcode = '22023'; end if;
    if v_sub.amount < least(coalesce(v_loan.monthly, 0), v_total) then
      raise exception 'Payment is below the required monthly due' using errcode = '22023';
    end if;
    insert into public.loan_payments(loan_id, member_id, amount, paid_at)
    values (v_sub.loan_id, v_sub.member_id, v_sub.amount, v_sub.paid_on);
    select coalesce(sum(amount), 0) into v_paid from public.loan_payments where loan_id = v_sub.loan_id;
    if v_paid >= v_loan.total then update public.loans set status = 'Paid' where id = v_sub.loan_id; end if;
  end if;

  update public.payment_submissions
  set status = p_decision, reviewed_at = now(), reviewed_by = auth.uid(),
      admin_remarks = nullif(trim(p_remarks), '')
  where id = p_submission_id returning * into v_sub;
  return v_sub;
end;
$$;

create or replace function private.available_fund_balance()
returns numeric
language sql
stable
security definer
set search_path = pg_catalog
as $$
  with group_weekly as (
    select week_start, sum(amount) as amount from public.payments group by week_start
  ),
  member_weekly as (
    select week_start, sum(amount) as amount
    from public.weekly_contribution_allocations group by week_start
  ),
  weekly as (
    select greatest(coalesce(g.amount, 0), coalesce(m.amount, 0)) as amount
    from group_weekly g full outer join member_weekly m using (week_start)
  )
  select coalesce((select sum(amount) from weekly), 0)
       + coalesce((select sum(amount) from public.loan_payments), 0)
       - coalesce((select sum(amount) from public.loans), 0);
$$;

revoke all on function public.submit_payment(text,numeric,date,date,bigint,text),
  public.review_payment_submission(bigint,text,text) from public, anon;
grant execute on function public.submit_payment(text,numeric,date,date,bigint,text),
  public.review_payment_submission(bigint,text,text) to authenticated;
