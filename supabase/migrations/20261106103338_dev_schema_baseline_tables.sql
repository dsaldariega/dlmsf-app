
create schema if not exists private;

create table public.members (
 id bigint generated by default as identity primary key,
 name text not null,
 heads integer not null default 1,
 created_at timestamp without time zone default now(),
 auth_id uuid,
 roles text[]
);

create table public.loans (
 id bigint generated by default as identity primary key,
 amount numeric,
 interest numeric,
 total numeric,
 monthly numeric,
 status text default 'Ongoing',
 borrower_id bigint references public.members(id) on delete cascade,
 months numeric
);

create table public.payments (
 id bigint generated by default as identity primary key,
 member_id bigint references public.members(id) on delete cascade,
 amount numeric not null,
 week_start date not null,
 created_at timestamp without time zone default now()
);

create table public.loans_audit_log (
 id bigint generated by default as identity primary key,
 amount numeric,
 interest numeric,
 total numeric,
 monthly numeric,
 action text,
 borrower_name text,
 months numeric,
 created_date date,
 remarks text,
 ref_id varchar,
 member_id bigint references public.members(id) on delete set null
);

create table public.payments_audit_log (
 id bigint generated by default as identity primary key,
 member_id bigint,
 amount numeric not null,
 week_start date not null,
 created_date timestamp without time zone default now(),
 ref_id varchar,
 remarks text,
 action text
);

create table public.audit_ref_counters (
 prefix text not null,
 ref_date date not null,
 last_number bigint not null default 0,
 primary key(prefix, ref_date)
);

create table public.loan_payments (
 id bigint generated by default as identity primary key,
 loan_id bigint references public.loans(id) on delete cascade,
 member_id bigint references public.members(id) on delete cascade,
 amount numeric not null,
 paid_at date not null,
 created_at timestamp without time zone default now()
);

create table public.loan_requests (
 id bigint generated by default as identity primary key,
 member_id bigint not null references public.members(id) on delete cascade,
 amount numeric(12,2) not null check(amount >= 500 and mod(amount,500)=0),
 months integer not null check(months in (1,2,3,4,5,6,9,12,18,24)),
 status text not null default 'Pending' check(status in ('Pending','Approved','Rejected')),
 requested_at timestamptz not null default now(),
 reviewed_at timestamptz,
 reviewed_by uuid,
 admin_remarks text,
 loan_id bigint references public.loans(id) on delete set null
);

create table public.payment_submissions (
 id bigint generated by default as identity primary key,
 member_id bigint not null references public.members(id) on delete cascade,
 payment_type text not null check(payment_type in ('Weekly','Loan')),
 amount numeric(12,2) not null check(amount > 0),
 paid_on date not null default current_date,
 week_start date,
 loan_id bigint references public.loans(id) on delete set null,
 reference text,
 status text not null default 'Pending' check(status in ('Pending','Confirmed','Rejected')),
 submitted_at timestamptz not null default now(),
 reviewed_at timestamptz,
 reviewed_by uuid,
 admin_remarks text,
 constraint payment_submission_target check(
   (payment_type='Weekly' and week_start is not null and extract(dow from week_start)=0 and loan_id is null)
   or (payment_type='Loan' and loan_id is not null and week_start is null)
 )
);

create table public.loan_request_audit_events (
 id bigint generated by default as identity primary key,
 loan_request_id bigint not null references public.loan_requests(id) on delete restrict,
 member_id bigint not null references public.members(id) on delete restrict,
 amount numeric not null,
 months integer not null,
 action text not null check(action in ('Requested','Approved','Rejected')),
 actor_id uuid,
 actor_role text not null check(actor_role in ('member','admin','system')),
 remarks text,
 created_at timestamptz not null default now()
);

create table public.weekly_contribution_allocations (
 id bigint generated by default as identity primary key,
 payment_submission_id bigint not null references public.payment_submissions(id) on delete cascade,
 member_id bigint not null references public.members(id) on delete cascade,
 week_start date not null check(extract(dow from week_start)=0),
 amount numeric(12,2) not null check(amount>0),
 created_at timestamptz not null default now(),
 unique(payment_submission_id, week_start)
);

create index idx_loan_payments_loan_id on public.loan_payments(loan_id);
create index idx_loan_payments_member_id on public.loan_payments(member_id);
create index loan_request_audit_events_member_created_idx on public.loan_request_audit_events(member_id, created_at desc);
create index loan_request_audit_events_request_idx on public.loan_request_audit_events(loan_request_id, created_at desc);
create unique index loan_requests_one_pending on public.loan_requests(member_id) where status='Pending';
create index loan_requests_status_idx on public.loan_requests(status, requested_at desc);
create index idx_loans_borrower_id on public.loans(borrower_id);
create unique index loans_audit_log_ref_id_unique on public.loans_audit_log(ref_id) where ref_id is not null;
create unique index payment_submissions_loan_pending_unique on public.payment_submissions(member_id,loan_id) where payment_type='Loan' and status='Pending';
create unique index payment_submissions_one_pending_weekly on public.payment_submissions(member_id) where payment_type='Weekly' and status='Pending';
create index payment_submissions_status_idx on public.payment_submissions(status, submitted_at desc);
create index idx_payments_member_id on public.payments(member_id);
create unique index payments_audit_log_ref_id_unique on public.payments_audit_log(ref_id) where ref_id is not null;
create index weekly_contribution_allocations_member_week_idx on public.weekly_contribution_allocations(member_id,week_start);

alter table public.members enable row level security;
alter table public.loans enable row level security;
alter table public.payments enable row level security;
alter table public.loans_audit_log enable row level security;
alter table public.payments_audit_log enable row level security;
alter table public.loan_payments enable row level security;
alter table public.loan_requests enable row level security;
alter table public.payment_submissions enable row level security;
alter table public.loan_request_audit_events enable row level security;
alter table public.weekly_contribution_allocations enable row level security;
